function addTableSheet(workbookInstance, sheetName, headers, rows, tableName, options = {}) {
  const sheet = workbookInstance.worksheets.add(sheetName);
  sheet.showGridLines = false;
  const rowCount = rows.length + 1;
  const colCount = headers.length;
  sheet.getRangeByIndexes(0, 0, 1, colCount).values = [headers];
  if (rows.length) {
    sheet.getRangeByIndexes(1, 0, rows.length, colCount).values = rows;
  }
  const used = sheet.getRangeByIndexes(0, 0, rowCount, colCount);
  used.format.wrapText = true;
  used.format.verticalAlignment = 'top';
  used.format.borders = { preset: 'all', style: 'thin', color: '#CBD5E1' };
  const header = sheet.getRangeByIndexes(0, 0, 1, colCount);
  header.format.fill = { color: '#0F172A' };
  header.format.font = { bold: true, color: '#FFFFFF' };
  header.format.rowHeightPx = 34;
  if (rows.length) {
    sheet.getRangeByIndexes(1, 0, rows.length, colCount).format.rowHeightPx = sheetName === 'Defects' ? 120 : 92;
  }
  const widths = options.widths || [];
  widths.forEach((width, colIndex) => {
    sheet.getRangeByIndexes(0, colIndex, rowCount, 1).format.columnWidthPx = width;
  });
  sheet.freezePanes.freezeRows(1);
  const tableRange = `A1:${columnName(colCount)}${rowCount}`;
  const table = sheet.tables.add(tableRange, true, tableName);
  table.style = 'TableStyleMedium2';
  table.showFilterButton = true;
  return sheet;
}

